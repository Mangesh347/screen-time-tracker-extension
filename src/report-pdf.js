// Client-side daily/weekly PDF report builder (jsPDF)
import { fmt, catColor } from './utils.js';

function ensureJsPDF() {
  const g = globalThis.jspdf?.jsPDF || globalThis.jsPDF;
  if (!g) throw new Error('jsPDF not loaded');
  return g;
}

export function buildReportPDF({ title, subtitle, total, score, topSites, catBreakdown, daily, insights }) {
  const JsPDF = ensureJsPDF();
  const doc = new JsPDF({ unit: 'pt', format: 'a4' });
  const W = doc.internal.pageSize.getWidth();
  let y = 48;

  // Header bar
  doc.setFillColor(12, 12, 14);
  doc.rect(0, 0, W, 90, 'F');
  doc.setFillColor(0, 229, 255);
  doc.rect(0, 90, W, 3, 'F');

  doc.setTextColor(0, 229, 255);
  doc.setFontSize(10);
  doc.text('SCREEN TIME TRACKER', 40, 36);
  doc.setTextColor(240, 240, 248);
  doc.setFontSize(22);
  doc.text(title || 'Usage Report', 40, 60);
  doc.setTextColor(152, 152, 176);
  doc.setFontSize(11);
  doc.text(subtitle || new Date().toLocaleDateString(), 40, 78);

  y = 120;
  // KPI cards
  const kpis = [
    ['Total Time', fmt(total)],
    ['Score', `${score}/100`],
    ['Sites', String(topSites?.length || 0)],
    ['Top Category', catBreakdown?.[0]?.category || '—'],
  ];
  const cardW = (W - 100) / 4;
  kpis.forEach((k, i) => {
    const x = 40 + i * (cardW + 6);
    doc.setFillColor(23, 23, 28);
    doc.roundedRect(x, y, cardW, 54, 6, 6, 'F');
    doc.setTextColor(82, 82, 106);
    doc.setFontSize(8);
    doc.text(k[0].toUpperCase(), x + 10, y + 18);
    doc.setTextColor(240, 240, 248);
    doc.setFontSize(14);
    doc.text(String(k[1]).slice(0, 14), x + 10, y + 40);
  });

  y += 80;
  doc.setTextColor(240, 240, 248);
  doc.setFontSize(13);
  doc.text('Top Sites', 40, y);
  y += 14;
  (topSites || []).slice(0, 10).forEach((s, i) => {
    doc.setFillColor(i % 2 ? 23 : 17, i % 2 ? 23 : 17, i % 2 ? 28 : 20);
    doc.roundedRect(40, y, W - 80, 18, 3, 3, 'F');
    doc.setTextColor(152, 152, 176);
    doc.setFontSize(9);
    doc.text(`${i + 1}. ${s.domain}`.slice(0, 48), 48, y + 12);
    doc.setTextColor(0, 229, 255);
    doc.text(fmt(s.totalTime || s.time || 0), W - 48, y + 12, { align: 'right' });
    y += 22;
  });

  y += 10;
  if (y > 680) { doc.addPage(); y = 48; }
  doc.setTextColor(240, 240, 248);
  doc.setFontSize(13);
  doc.text('Categories', 40, y);
  y += 16;
  (catBreakdown || []).slice(0, 8).forEach(c => {
    const pct = total ? Math.round((c.time / total) * 100) : 0;
    const barW = Math.max(4, ((W - 180) * pct) / 100);
    const hex = catColor(c.category);
    const rgb = hexToRgb(hex);
    doc.setTextColor(152, 152, 176);
    doc.setFontSize(9);
    doc.text(c.category, 40, y + 8);
    doc.setFillColor(38, 38, 47);
    doc.roundedRect(120, y, W - 220, 8, 3, 3, 'F');
    doc.setFillColor(rgb[0], rgb[1], rgb[2]);
    doc.roundedRect(120, y, barW, 8, 3, 3, 'F');
    doc.setTextColor(240, 240, 248);
    doc.text(`${fmt(c.time)} (${pct}%)`, W - 40, y + 8, { align: 'right' });
    y += 18;
  });

  if (daily?.length) {
    y += 16;
    if (y > 700) { doc.addPage(); y = 48; }
    doc.setTextColor(240, 240, 248);
    doc.setFontSize(13);
    doc.text('Daily Trend', 40, y);
    y += 12;
    const max = Math.max(...daily.map(d => d.time), 1);
    const chartH = 70;
    const chartW = W - 80;
    const bw = chartW / daily.length;
    daily.forEach((d, i) => {
      const h = Math.max(2, (d.time / max) * chartH);
      const x = 40 + i * bw;
      const alpha = 0.35 + (d.time / max) * 0.65;
      doc.setFillColor(0, Math.round(229 * alpha), Math.round(255 * alpha));
      doc.roundedRect(x + bw * 0.15, y + chartH - h, bw * 0.7, h, 2, 2, 'F');
    });
    y += chartH + 20;
  }

  if (insights?.length) {
    if (y > 680) { doc.addPage(); y = 48; }
    doc.setTextColor(240, 240, 248);
    doc.setFontSize(13);
    doc.text('Insights', 40, y);
    y += 14;
    insights.slice(0, 5).forEach(ins => {
      doc.setTextColor(152, 152, 176);
      doc.setFontSize(9);
      const lines = doc.splitTextToSize(`• ${ins.title}: ${ins.desc}`, W - 80);
      doc.text(lines, 40, y);
      y += lines.length * 12 + 6;
    });
  }

  doc.setTextColor(82, 82, 106);
  doc.setFontSize(8);
  doc.text('Generated by Screen Time Tracker', 40, doc.internal.pageSize.getHeight() - 24);

  return doc;
}

function hexToRgb(hex) {
  const h = (hex || '#4488ff').replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

export function pdfToBase64(doc) {
  return doc.output('datauristring').split(',')[1];
}

export function downloadPDF(doc, filename) {
  doc.save(filename || `screen-time-${new Date().toISOString().slice(0, 10)}.pdf`);
}
